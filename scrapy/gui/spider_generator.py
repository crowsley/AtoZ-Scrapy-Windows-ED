"""
Scrapy Pro Enterprise Architecture - AI Spider Generator

Automatically generates complete Scrapy Spider code from a target URL and selector specs.
"""

import os


def generate_spider_code(spider_name: str, start_url: str, allowed_domain: str = "") -> str:
    domain = allowed_domain or start_url.split("//")[-1].split("/")[0]

    code = f'''# Auto-generated by Scrapy Pro AI Spider Generator
import scrapy


class {spider_name.capitalize()}Spider(scrapy.Spider):
    name = "{spider_name}"
    allowed_domains = ["{domain}"]
    start_urls = ["{start_url}"]

    custom_settings = {{
        "ITEM_PIPELINES": {{
            "scrapy.pipelines.gui_pipeline.GuiItemPipeline": 100,
        }},
        "CONCURRENT_REQUESTS": 16,
    }}

    def parse(self, response):
        for item in response.css("div, article, tr"):
            yield {{
                "title": item.css("h1::text, h2::text, h3::text, a::text").get(),
                "link": response.urljoin(item.css("a::attr(href)").get() or ""),
                "text": item.css("p::text, span::text").get(),
                "url": response.url,
            }}

        next_page = response.css("a.next::attr(href), li.next a::attr(href)").get()
        if next_page:
            yield response.follow(next_page, self.parse)
'''
    return code


def save_generated_spider(spider_name: str, start_url: str, target_dir: str = r"c:\Users\saghi\Downloads\Scrapy\scrapy\spiders") -> str:
    code = generate_spider_code(spider_name, start_url)
    filepath = os.path.join(target_dir, f"{spider_name}_spider.py")
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(code)
    return filepath
